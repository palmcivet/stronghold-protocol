/** A catalog entry: the Chinese source and an optional note for translators. */
export interface CatalogEntry {
  readonly source: string;
  readonly note?: string;
}

const entry = <const S extends string>(
  source: S,
  note?: string,
): { readonly source: S; readonly note?: string } =>
  note === undefined ? { source } : { source, note };

