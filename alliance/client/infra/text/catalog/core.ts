const phaseEntries = Object.fromEntries(
  Object.entries(PHASE_NAMES).map(([phase, source]) => [
    `core:phase.${phase}`,
    { source },
  ]),
) as Readonly<Record<`core:phase.${string}`, CatalogEntry>>;

/** Server text. Its sources are the master msgids, so the msgid table is generated from them. */
export const SERVER: Readonly<Record<`server:${string}`, CatalogEntry>> =
  Object.fromEntries(
    Object.entries(ERR_TEXT).map(([code, source]) => [
      `server:error.${code}`,
      { source },
    ]),
  );

export const PHASES: Readonly<Record<`core:phase.${string}`, CatalogEntry>> =
  phaseEntries;
